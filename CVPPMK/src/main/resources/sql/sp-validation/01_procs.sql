-- 4.4 Stored procedure validasi transaksi (SBO_SP_TransactionNotification dkk.)
SELECT PROCEDURE_NAME AS "Name", LENGTH(DEFINITION) AS "Len", DEFINITION AS "Definition"
FROM SYS.PROCEDURES
WHERE SCHEMA_NAME = CURRENT_SCHEMA AND PROCEDURE_NAME IN ('SBO_SP_TRANSACTIONNOTIFICATION', 'SBO_SP_POSTTRANSACTIONNOTICE', 'SBO_SP_EDF_TRANSACTIONNOTIFICATION')
ORDER BY PROCEDURE_NAME
