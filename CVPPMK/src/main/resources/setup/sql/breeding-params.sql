-- Setup F · Parameter Farm Breeding Addon -> @ST_PARAM via entity U_ST_PARAM. Hanya key yang dibaca kode Farm Breeding Addon 1.03.
-- Code dan Name = U_Key (sama di sumber dan tujuan, jadi tidak bentrok); _key = Code asli, dipakai untuk update.
SELECT "Code" AS "_key", "U_Key" AS "Code", "U_Key" AS "Name", "U_Key", "U_Value", "U_Desc"
FROM "@ST_PARAM"
WHERE "U_Key" IN (
  'STATSETTERWHS', 'STATHATCHFINALWHS', 'STATHATCHDESTWHS', 'WHTRS', 'STATEGG', 'STATDOC',
  'STATRECEIVECHICK', 'STATFEEDPROD', 'STATFEEDGROW', 'STATCULLCHICKGROW', 'STATCREATEAUTOGI', 'STATMALE',
  'STATFEMALE', 'STATAFKHDP', 'STATSRSGI', 'STATSRSGR', 'JESRS', 'SRSIT',
  'ACTWIPCOMMERCIALEGG', 'ACTWIPPROD', 'ACTWIPDAILYPROD', 'ITMHE', 'ITMGRPCHICK', 'ITMGRPHE',
  'ITMGRPNONHE', 'ITMGRPDOC', 'ITMGRPFEED', 'ITMAFKHDP', 'MAXDAYBACKDATEDSTATISTIC', 'REMAINLIFE',
  'OUTSDUEDATE', 'OUTHDUEDATE', 'ALLOWZEROOUTSETTER', 'STDALSBY', 'PREFATSTD', 'USERAUTHDUPLICATE')
ORDER BY "U_Key"
